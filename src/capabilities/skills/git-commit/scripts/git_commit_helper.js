'use strict';

var childProcess = require('child_process');
var crypto = require('crypto');
var fs = require('fs');
var path = require('path');

var GENERATED_PATH_PATTERNS = [
    /^res_[^/]+\/flavor\/index\.html$/,
    /^res_[^/]+\/flavor\/main[^/]*\.css$/,
    /^res_[^/]+\/flavor\/project\.json$/,
    /^res_[^/]+\/flavor\/js_src\/common\/util\/Config\.js$/,
    /^res_[^/]+\/resource_list\/.+\.json$/
];
var AI_MARKER_PATTERNS = [
    /generated with claude/i,
    /co-authored-by:\s*claude/i,
    /generated by (?:an )?ai/i,
    /ai\s*生成/i
];

/**
 * Stop the current command with a structured user-facing error.
 * @param {string} message Error summary.
 * @param {*} details Relevant diagnostic details.
 * @param {number} exitCode Process exit code.
 * @returns {void}
 */
function fail(message, details, exitCode) {
    var error = new Error(message);
    error.details = details || null;
    error.exitCode = exitCode || 1;
    throw error;
}

/**
 * Execute Git without a shell so paths and messages remain literal arguments.
 * @param {string} repository Git repository root.
 * @param {string[]} args Git arguments.
 * @param {boolean} allowFailure Whether a non-zero result should be returned.
 * @returns {Object} spawnSync result.
 */
function runGit(repository, args, allowFailure) {
    var result = childProcess.spawnSync('git', ['-C', repository].concat(args), {
        encoding: 'utf8'
    });
    if (result.error) {
        fail('无法执行 Git', result.error.message);
    }
    if (!allowFailure && result.status !== 0) {
        fail('Git 命令失败', {
            args: args,
            status: result.status,
            stdout: String(result.stdout || ''),
            stderr: String(result.stderr || '')
        });
    }
    return result;
}

function processOutput(result) {
    return [String(result.stdout || '').trim(), String(result.stderr || '').trim()]
        .filter(function (value) {
            return value !== '';
        }).join('\n');
}

function gitText(repository, args) {
    return String(runGit(repository, args, false).stdout || '').trim();
}

function optionalGitText(repository, args) {
    var result = runGit(repository, args, true);
    return result.status === 0 ? String(result.stdout || '').trim() : null;
}

function zeroList(value) {
    return String(value || '').split('\0').filter(function (item) {
        return item !== '';
    });
}

function uniqueSorted(values) {
    var seen = Object.create(null);
    return values.filter(function (value) {
        if (seen[value]) {
            return false;
        }
        seen[value] = true;
        return true;
    }).sort();
}

function sameValues(left, right) {
    return JSON.stringify(uniqueSorted(left)) === JSON.stringify(uniqueSorted(right));
}

function sha256(value) {
    return 'sha256:' + crypto.createHash('sha256').update(value).digest('hex');
}

/**
 * Parse repeated CLI options used by all helper commands.
 * @param {string[]} argv Process argument vector.
 * @returns {Object} Parsed command options.
 */
function parseArguments(argv) {
    var parsed = {
        command: argv[2] || '',
        repo: '.',
        paths: [],
        messages: []
    };
    var index;
    var key;
    var value;
    for (index = 3; index < argv.length; index += 2) {
        key = argv[index];
        value = argv[index + 1];
        if (!key || key.slice(0, 2) !== '--' || typeof value === 'undefined') {
            fail('参数必须使用 --name value 形式', { index: index, value: key });
        }
        if (key === '--repo') {
            parsed.repo = value;
        } else if (key === '--path') {
            parsed.paths.push(value);
        } else if (key === '--message') {
            parsed.messages.push(value);
        } else if (key === '--expected-head') {
            parsed.expectedHead = value;
        } else if (key === '--expected-scope-digest') {
            parsed.expectedScopeDigest = value;
        } else if (key === '--commit') {
            parsed.commit = value;
        } else {
            fail('未知参数', key);
        }
    }
    return parsed;
}

/**
 * Resolve and validate the target Git repository.
 * @param {string} repository Requested repository path.
 * @returns {string} Canonical repository root.
 */
function resolveRepository(repository) {
    var requested = path.resolve(repository);
    var root = optionalGitText(requested, ['rev-parse', '--show-toplevel']);
    if (!root) {
        fail('目标不是 Git 仓库', repository);
    }
    return path.resolve(root);
}

/**
 * Normalize explicit file paths and reject directories or paths outside the repo.
 * @param {string} repository Canonical repository root.
 * @param {string[]} values Requested paths.
 * @returns {string[]} Sorted repository-relative paths.
 */
function normalizePaths(repository, values) {
    var normalized;
    if (!values.length) {
        fail('至少需要一个 --path');
    }
    normalized = values.map(function (value) {
        var absolute = path.resolve(repository, value);
        var relative = path.relative(repository, absolute).split(path.sep).join('/');
        var stat;
        if (!relative || relative === '..' || relative.slice(0, 3) === '../' ||
                path.isAbsolute(relative)) {
            fail('提交路径必须位于仓库内', value);
        }
        if (fs.existsSync(absolute)) {
            stat = fs.lstatSync(absolute);
            if (stat.isDirectory()) {
                fail('提交路径必须精确到文件，不能使用目录', relative);
            }
        }
        return relative;
    });
    if (uniqueSorted(normalized).length !== normalized.length) {
        fail('提交路径存在重复项', normalized);
    }
    return normalized.sort();
}

function isGeneratedPath(filePath) {
    return GENERATED_PATH_PATTERNS.some(function (pattern) {
        return pattern.test(filePath);
    });
}

/**
 * Fingerprint current file content, type, mode and size without following symlinks.
 * @param {string} repository Canonical repository root.
 * @param {string} filePath Repository-relative file path.
 * @returns {string} Stable current-worktree fingerprint.
 */
function pathFingerprint(repository, filePath) {
    var absolute = path.join(repository, filePath);
    var stat;
    var content;
    try {
        stat = fs.lstatSync(absolute);
    } catch (error) {
        if (error.code === 'ENOENT') {
            return 'missing';
        }
        throw error;
    }
    if (stat.isDirectory()) {
        fail('提交路径必须精确到文件，不能使用目录', filePath);
    }
    if (stat.isSymbolicLink()) {
        content = Buffer.from('symlink:' + fs.readlinkSync(absolute), 'utf8');
    } else {
        content = fs.readFileSync(absolute);
    }
    return [stat.mode, stat.size, sha256(content)].join(':');
}

/**
 * Return every tracked or untracked worktree change without rename collapsing.
 * @param {string} repository Canonical repository root.
 * @returns {string[]} Changed repository-relative paths.
 */
function getChangedPaths(repository) {
    var tracked = zeroList(runGit(repository, [
        'diff', '--no-renames', '--name-only', '-z', 'HEAD', '--'
    ], false).stdout);
    var untracked = zeroList(runGit(repository, [
        'ls-files', '--others', '--exclude-standard', '-z', '--'
    ], false).stdout);
    return uniqueSorted(tracked.concat(untracked));
}

function getStagedPaths(repository) {
    return uniqueSorted(zeroList(runGit(repository, [
        'diff', '--cached', '--no-renames', '--name-only', '-z', '--'
    ], false).stdout));
}

/**
 * Bind a preflight decision to task content and index state.
 * @param {string} repository Canonical repository root.
 * @param {string[]} requestedPaths Exact task paths.
 * @param {string[]} changedPaths Current changed paths.
 * @param {string[]} stagedPaths Current staged paths.
 * @param {Object} identity Current branch and upstream identity.
 * @returns {string} Scope digest.
 */
function getScopeDigest(repository, requestedPaths, changedPaths, stagedPaths, identity) {
    var entries = requestedPaths.map(function (filePath) {
        return {
            path: filePath,
            changed: changedPaths.indexOf(filePath) !== -1,
            staged: stagedPaths.indexOf(filePath) !== -1,
            fingerprint: pathFingerprint(repository, filePath)
        };
    });
    return sha256(Buffer.from(JSON.stringify({
        identity: identity,
        entries: entries
    }), 'utf8'));
}

function getContentDigest(repository, requestedPaths) {
    var entries = requestedPaths.map(function (filePath) {
        return {
            path: filePath,
            fingerprint: pathFingerprint(repository, filePath)
        };
    });
    return sha256(Buffer.from(JSON.stringify(entries), 'utf8'));
}

function getAheadBehind(repository, upstream) {
    var counts;
    if (!upstream) {
        return { ahead: null, behind: null };
    }
    counts = gitText(repository, [
        'rev-list', '--left-right', '--count', 'HEAD...@{upstream}'
    ]).split(/\s+/).map(Number);
    return { ahead: counts[0], behind: counts[1] };
}

/**
 * Collect one deterministic snapshot for range and synchronization decisions.
 * @param {string} repository Canonical repository root.
 * @param {string[]} requestedPaths Exact task paths.
 * @returns {Object} Structured repository state.
 */
function getState(repository, requestedPaths) {
    var head = gitText(repository, ['rev-parse', 'HEAD']);
    var branch = gitText(repository, ['branch', '--show-current']);
    var upstream = optionalGitText(repository, [
        'rev-parse', '--abbrev-ref', '--symbolic-full-name', '@{upstream}'
    ]);
    var remote = branch ? optionalGitText(repository, [
        'config', '--get', 'branch.' + branch + '.remote'
    ]) : null;
    var changedPaths = getChangedPaths(repository);
    var stagedPaths = getStagedPaths(repository);
    var requestedChanges = requestedPaths.filter(function (filePath) {
        return changedPaths.indexOf(filePath) !== -1;
    });
    var otherChanges = changedPaths.filter(function (filePath) {
        return requestedPaths.indexOf(filePath) === -1;
    });
    var generatedPaths = requestedPaths.filter(isGeneratedPath);
    var aheadBehind = getAheadBehind(repository, upstream);
    var stashList = optionalGitText(repository, ['stash', 'list', '--format=%gd']);
    var state = {
        schemaVersion: 1,
        head: head,
        branch: branch || null,
        upstream: upstream,
        remote: remote,
        ahead: aheadBehind.ahead,
        behind: aheadBehind.behind,
        stashCount: stashList ? stashList.split('\n').length : 0,
        requestedPaths: requestedPaths,
        requestedChanges: requestedChanges,
        unchangedPaths: requestedPaths.filter(function (filePath) {
            return requestedChanges.indexOf(filePath) === -1;
        }),
        generatedPaths: generatedPaths,
        stagedPaths: stagedPaths,
        otherChanges: otherChanges.slice(0, 200),
        otherChangeCount: otherChanges.length,
        otherChangesTruncated: otherChanges.length > 200,
        scopeDigest: getScopeDigest(repository, requestedPaths, changedPaths, stagedPaths, {
            branch: branch || null,
            upstream: upstream,
            remote: remote
        }),
        contentDigest: getContentDigest(repository, requestedPaths)
    };
    state.scopeReady = Boolean(state.branch && state.upstream && state.remote &&
        state.remote !== '.' &&
        state.unchangedPaths.length === 0 && state.generatedPaths.length === 0 &&
        state.stagedPaths.length === 0);
    state.canCommit = state.scopeReady && state.behind === 0;
    return state;
}

function printJson(value) {
    process.stdout.write(JSON.stringify(value, null, 2) + '\n');
}

/**
 * Verify that the reviewed HEAD, scope and index still match preflight.
 * @param {Object} state Current repository state.
 * @param {Object} parsed Expected state arguments.
 * @returns {void}
 */
function assertExpectedState(state, parsed) {
    if (!parsed.expectedHead || !parsed.expectedScopeDigest) {
        fail('缺少 --expected-head 或 --expected-scope-digest');
    }
    if (state.head !== parsed.expectedHead) {
        fail('HEAD 已漂移', { expected: parsed.expectedHead, actual: state.head }, 2);
    }
    if (state.scopeDigest !== parsed.expectedScopeDigest) {
        fail('提交范围已漂移', {
            expected: parsed.expectedScopeDigest,
            actual: state.scopeDigest
        }, 2);
    }
    if (!state.scopeReady) {
        fail('当前状态不满足确定性提交条件', state, 2);
    }
}

/**
 * Enforce a detailed message and reject known AI attribution markers.
 * @param {string[]} messages Git message paragraphs.
 * @returns {void}
 */
function validateMessages(messages) {
    var joined;
    if (messages.length < 2 || !messages[0].trim() || !messages[1].trim()) {
        fail('提交信息必须包含标题和至少一段真实变更详情');
    }
    joined = messages.join('\n\n');
    AI_MARKER_PATTERNS.forEach(function (pattern) {
        if (pattern.test(joined)) {
            fail('提交信息包含 AI 生成标记', pattern.source);
        }
    });
}

function commandPreflight(repository, requestedPaths) {
    var state = getState(repository, requestedPaths);
    printJson({ ok: state.canCommit, state: state });
}

function commandSyncCheck(repository, requestedPaths, parsed) {
    var state = getState(repository, requestedPaths);
    assertExpectedState(state, parsed);
    if (state.behind !== 0) {
        fail('远端包含本地尚未取得的提交', state, 3);
    }
    printJson({ ok: true, state: state });
}

/**
 * Validate local scope, refresh the configured remote and bind the result.
 * @param {string} repository Canonical repository root.
 * @param {string[]} requestedPaths Exact task paths.
 * @returns {void}
 */
function commandPrepare(repository, requestedPaths) {
    var before = getState(repository, requestedPaths);
    var fetchResult;
    var after;
    if (!before.scopeReady) {
        fail('当前状态不满足确定性提交条件', before, 2);
    }
    fetchResult = runGit(repository, ['fetch', before.remote], true);
    if (fetchResult.status !== 0) {
        fail('获取远端状态失败', {
            remote: before.remote,
            output: processOutput(fetchResult)
        }, 5);
    }
    after = getState(repository, requestedPaths);
    assertExpectedState(after, {
        expectedHead: before.head,
        expectedScopeDigest: before.scopeDigest
    });
    if (after.behind !== 0) {
        fail('远端包含本地尚未取得的提交', after, 3);
    }
    printJson({
        ok: true,
        phase: 'prepared',
        state: after,
        fetch: {
            remote: before.remote,
            output: processOutput(fetchResult)
        },
        token: {
            head: after.head,
            scopeDigest: after.scopeDigest
        }
    });
}

function getCommittedPaths(repository, commit) {
    return uniqueSorted(zeroList(runGit(repository, [
        'diff-tree', '--root', '--no-commit-id', '--no-renames',
        '--name-only', '-r', '-z', commit, '--'
    ], false).stdout));
}

/**
 * Apply deterministic staging checks and create one commit in one invocation.
 * @param {string} repository Canonical repository root.
 * @param {string[]} requestedPaths Exact task paths.
 * @param {Object} parsed Expected state and commit message arguments.
 * @returns {void}
 */
function createCommit(repository, requestedPaths, parsed) {
    var state;
    var contentDigest;
    var stagedPaths;
    var commitArgs = ['commit'];
    var commitResult;
    var commitHash;
    var committedPaths;
    validateMessages(parsed.messages);
    state = getState(repository, requestedPaths);
    assertExpectedState(state, parsed);
    if (state.behind !== 0) {
        fail('远端包含本地尚未取得的提交', state, 3);
    }
    contentDigest = state.contentDigest;
    runGit(repository, ['add', '--'].concat(requestedPaths), false);
    if (getContentDigest(repository, requestedPaths) !== contentDigest) {
        fail('精确暂存期间任务文件发生变化', requestedPaths, 2);
    }
    stagedPaths = getStagedPaths(repository);
    if (!sameValues(stagedPaths, requestedPaths)) {
        fail('暂存范围与请求路径不一致', {
            requestedPaths: requestedPaths,
            stagedPaths: stagedPaths
        }, 4);
    }
    runGit(repository, ['diff', '--cached', '--check'], false);
    parsed.messages.forEach(function (message) {
        commitArgs.push('-m', message);
    });
    commitResult = runGit(repository, commitArgs, false);
    commitHash = gitText(repository, ['rev-parse', 'HEAD']);
    committedPaths = getCommittedPaths(repository, commitHash);
    if (!sameValues(committedPaths, requestedPaths)) {
        fail('最终提交范围与请求路径不一致', {
            commit: commitHash,
            requestedPaths: requestedPaths,
            committedPaths: committedPaths
        }, 4);
    }
    return {
        ok: true,
        commit: commitHash,
        output: String(commitResult.stdout || '').trim(),
        committedPaths: committedPaths,
        sourceState: state
    };
}

function publicCommitResult(result) {
    return {
        ok: result.ok,
        commit: result.commit,
        output: result.output,
        committedPaths: result.committedPaths
    };
}

function commandCommit(repository, requestedPaths, parsed) {
    printJson(publicCommitResult(createCommit(repository, requestedPaths, parsed)));
}

/**
 * Read commit metadata without embedding a human-formatted Git log.
 * @param {string} repository Canonical repository root.
 * @param {string} commit Full commit hash.
 * @returns {Object} Structured commit metadata.
 */
function getCommitMetadata(repository, commit) {
    var output = String(runGit(repository, [
        'show', '-s', '--format=%H%x00%cn%x00%ce%x00%s%x00%b%x00',
        commit
    ], false).stdout || '');
    var fields = output.split('\0');
    if (fields.length < 6 || fields[0] !== commit) {
        fail('无法解析提交元数据', { commit: commit });
    }
    return {
        hash: fields[0],
        committer: {
            name: fields[1],
            email: fields[2]
        },
        message: {
            title: fields[3],
            body: fields[4].replace(/\n+$/, '')
        }
    };
}

/**
 * Read raw file modes and status for every path in a commit.
 * @param {string} repository Canonical repository root.
 * @param {string} commit Full commit hash.
 * @returns {Object} File details keyed by repository-relative path.
 */
function getRawFileChanges(repository, commit) {
    var records = zeroList(runGit(repository, [
        'diff-tree', '--root', '--no-commit-id', '--no-renames', '--raw', '-r', '-z',
        commit, '--'
    ], false).stdout);
    var changes = Object.create(null);
    var index;
    var header;
    var parts;
    var filePath;
    for (index = 0; index < records.length; index += 2) {
        header = records[index];
        filePath = records[index + 1];
        parts = header.split(/\s+/);
        if (!filePath || parts.length < 5 || parts[0].charAt(0) !== ':') {
            fail('无法解析提交文件状态', { commit: commit, record: header });
        }
        changes[filePath] = {
            status: parts[4],
            oldMode: parts[0].slice(1),
            newMode: parts[1]
        };
    }
    return changes;
}

/**
 * Read additions and deletions for every path in a commit.
 * @param {string} repository Canonical repository root.
 * @param {string} commit Full commit hash.
 * @returns {Object} Numstat details keyed by repository-relative path.
 */
function getNumstat(repository, commit) {
    var records = zeroList(runGit(repository, [
        'show', '--no-renames', '--format=', '--numstat', '-z', commit, '--'
    ], false).stdout);
    var stats = Object.create(null);
    records.forEach(function (record) {
        var firstTab = record.indexOf('\t');
        var secondTab = record.indexOf('\t', firstTab + 1);
        var additions;
        var deletions;
        var filePath;
        if (firstTab === -1 || secondTab === -1) {
            fail('无法解析提交文件统计', { commit: commit, record: record });
        }
        additions = record.slice(0, firstTab);
        deletions = record.slice(firstTab + 1, secondTab);
        filePath = record.slice(secondTab + 1);
        stats[filePath] = {
            additions: additions === '-' ? null : Number(additions),
            deletions: deletions === '-' ? null : Number(deletions),
            binary: additions === '-' || deletions === '-'
        };
    });
    return stats;
}

/**
 * Build complete structured commit information for successful delivery output.
 * @param {string} repository Canonical repository root.
 * @param {string} commit Full commit hash.
 * @returns {Object} Metadata, file changes and aggregate statistics.
 */
function getCommitInfo(repository, commit) {
    var metadata = getCommitMetadata(repository, commit);
    var rawChanges = getRawFileChanges(repository, commit);
    var numstat = getNumstat(repository, commit);
    var paths = uniqueSorted(Object.keys(rawChanges).concat(Object.keys(numstat)));
    var insertions = 0;
    var deletions = 0;
    var binaryFiles = 0;
    metadata.files = paths.map(function (filePath) {
        var raw = rawChanges[filePath];
        var stat = numstat[filePath];
        if (!raw || !stat) {
            fail('提交文件详情不完整', { commit: commit, path: filePath });
        }
        if (stat.binary) {
            binaryFiles += 1;
        } else {
            insertions += stat.additions;
            deletions += stat.deletions;
        }
        return {
            path: filePath,
            status: raw.status,
            additions: stat.additions,
            deletions: stat.deletions,
            binary: stat.binary,
            modeChange: raw.oldMode === raw.newMode ? null : {
                from: raw.oldMode,
                to: raw.newMode
            }
        };
    });
    metadata.summary = {
        filesChanged: metadata.files.length,
        insertions: insertions,
        deletions: deletions,
        binaryFiles: binaryFiles
    };
    return metadata;
}

function getFullReport(repository, commit) {
    return String(runGit(repository, [
        '-c', 'core.quotePath=false',
        'show', '--no-renames', '--format=fuller', '--stat', '--summary', commit
    ], false).stdout || '');
}

/**
 * Emit a raw full Git log for explicit diagnostics.
 * @param {string} repository Canonical repository root.
 * @param {string} commit Full commit hash.
 * @returns {void}
 */
function commandReport(repository, commit) {
    if (!commit || !/^[0-9a-f]{40}$/.test(commit)) {
        fail('report 命令需要完整的 40 位 commit hash');
    }
    process.stdout.write(getFullReport(repository, commit));
}

/**
 * Commit, push the configured upstream and return the complete delivery proof.
 * @param {string} repository Canonical repository root.
 * @param {string[]} requestedPaths Exact task paths.
 * @param {Object} parsed Expected state and commit message arguments.
 * @returns {void}
 */
function commandDeliver(repository, requestedPaths, parsed) {
    var commitResult = createCommit(repository, requestedPaths, parsed);
    var state = commitResult.sourceState;
    var stagedAfterCommit = getStagedPaths(repository);
    var mergeRef;
    var refspec;
    var commitInfo;
    var pushResult;
    var pushOutput;
    var currentHead;
    var currentBranch;
    var currentUpstream;
    var currentRemote;
    var aheadBehind;
    var remainingChanges;
    if (stagedAfterCommit.length !== 0) {
        fail('提交后暂存区出现额外内容，已停止推送', {
            commit: commitResult.commit,
            stagedPaths: stagedAfterCommit
        }, 4);
    }
    currentHead = gitText(repository, ['rev-parse', 'HEAD']);
    currentBranch = gitText(repository, ['branch', '--show-current']);
    currentUpstream = optionalGitText(repository, [
        'rev-parse', '--abbrev-ref', '--symbolic-full-name', '@{upstream}'
    ]);
    currentRemote = currentBranch ? optionalGitText(repository, [
        'config', '--get', 'branch.' + currentBranch + '.remote'
    ]) : null;
    if (currentHead !== commitResult.commit || currentBranch !== state.branch ||
            currentUpstream !== state.upstream || currentRemote !== state.remote) {
        fail('提交后仓库身份发生漂移，已停止推送', {
            commit: commitResult.commit,
            actualHead: currentHead,
            expectedBranch: state.branch,
            actualBranch: currentBranch,
            expectedUpstream: state.upstream,
            actualUpstream: currentUpstream,
            expectedRemote: state.remote,
            actualRemote: currentRemote
        }, 2);
    }
    mergeRef = optionalGitText(repository, [
        'config', '--get', 'branch.' + state.branch + '.merge'
    ]);
    if (!mergeRef || mergeRef.slice(0, 11) !== 'refs/heads/') {
        fail('无法确定 upstream 远端分支，已停止推送', {
            commit: commitResult.commit,
            branch: state.branch,
            mergeRef: mergeRef
        }, 2);
    }
    commitInfo = getCommitInfo(repository, commitResult.commit);
    refspec = 'HEAD:' + mergeRef;
    pushResult = runGit(repository, ['push', state.remote, refspec], true);
    pushOutput = processOutput(pushResult);
    if (pushResult.status !== 0) {
        if (/non-fast-forward|fetch first|\[rejected\]/i.test(pushOutput)) {
            fail('推送被 non-fast-forward 拒绝', {
                commit: commitResult.commit,
                remote: state.remote,
                refspec: refspec,
                output: pushOutput
            }, 6);
        }
        fail('推送失败', {
            commit: commitResult.commit,
            remote: state.remote,
            refspec: refspec,
            output: pushOutput
        }, 5);
    }
    aheadBehind = getAheadBehind(repository, state.upstream);
    if (aheadBehind.ahead !== 0 || aheadBehind.behind !== 0) {
        fail('推送后本地与 upstream 未完全同步', {
            commit: commitResult.commit,
            upstream: state.upstream,
            ahead: aheadBehind.ahead,
            behind: aheadBehind.behind,
            output: pushOutput
        }, 5);
    }
    remainingChanges = getChangedPaths(repository);
    printJson({
        ok: true,
        phase: 'delivered',
        commitInfo: commitInfo,
        delivery: {
            status: 'pushed',
            branch: state.branch,
            ahead: aheadBehind.ahead,
            behind: aheadBehind.behind
        },
        remainingChanges: {
            count: remainingChanges.length,
            paths: remainingChanges.slice(0, 200),
            truncated: remainingChanges.length > 200
        }
    });
}

/**
 * Dispatch one helper command.
 * @returns {void}
 */
function main() {
    var parsed = parseArguments(process.argv);
    var repository = resolveRepository(parsed.repo);
    var requestedPaths;
    if (parsed.command === 'report') {
        commandReport(repository, parsed.commit);
        return;
    }
    requestedPaths = normalizePaths(repository, parsed.paths);
    if (parsed.command === 'preflight') {
        commandPreflight(repository, requestedPaths);
    } else if (parsed.command === 'sync-check') {
        commandSyncCheck(repository, requestedPaths, parsed);
    } else if (parsed.command === 'prepare') {
        commandPrepare(repository, requestedPaths);
    } else if (parsed.command === 'commit') {
        commandCommit(repository, requestedPaths, parsed);
    } else if (parsed.command === 'deliver') {
        commandDeliver(repository, requestedPaths, parsed);
    } else {
        fail('命令必须是 prepare、deliver、preflight、sync-check、commit 或 report',
            parsed.command);
    }
}

try {
    main();
} catch (error) {
    process.stderr.write(JSON.stringify({
        ok: false,
        error: error.message || String(error),
        details: error.details || null
    }, null, 2) + '\n');
    process.exitCode = error.exitCode || 1;
}
